export type I18nMessages = (typeof messages)['zh'];

function loadStoredLocale(): AppLocale {
  const stored = localStorage.getItem(STORAGE_KEY);
  if (stored === 'zh' || stored === 'en' || stored === 'ja') return stored;
  return 'en';
}

export const locale = ref<AppLocale>(loadStoredLocale());

function htmlLangTag(l: AppLocale): string {
  if (l === 'zh') return 'zh-CN';
  if (l === 'ja') return 'ja';
  return 'en';
}

export function localeCompareTag(l: AppLocale = locale.value): string {
  return htmlLangTag(l);
}

export function initLocale() {
  document.documentElement.lang = htmlLangTag(locale.value);
}

export function setLocale(next: AppLocale) {
  locale.value = next;
  localStorage.setItem(STORAGE_KEY, next);
  document.documentElement.lang = htmlLangTag(next);
}

type ParamValue = string | number;

function interpolate(text: string, params?: Record<string, ParamValue>) {
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (_, key: string) => String(params[key] ?? `{${key}}`));
}

function getNestedMessage(dict: I18nMessages, path: string): string | undefined {
  const parts = path.split('.');
  let current: unknown = dict;
  for (const part of parts) {
    if (current == null || typeof current !== 'object') return undefined;
    current = (current as Record<string, unknown>)[part];
  }
  return typeof current === 'string' ? current : undefined;
}

/** Translate by dot path, e.g. t('sidebar.addHost') */
export function t(path: string, params?: Record<string, ParamValue>): string {
  const current = getNestedMessage(messages[locale.value], path)
    ?? getNestedMessage(messages.en, path)
    ?? path;
  return interpolate(current, params);
}

export function useI18n() {
  const tr = computed(() => messages[locale.value]);
  return { locale, tr, setLocale, localeOptions, t };
}

export function sessionStatusLabel(status: SessionStatus | undefined, isLocal: boolean) {
  const s = messages[locale.value].session;
  if (isLocal) {
    if (status === 'connected') return s.local;
    if (status === 'connecting') return s.localStarting;
    if (status === 'failed') return s.localFailed;
    return s.local;
  }
  switch (status) {
    case 'connecting': return s.connecting;
    case 'connected': return s.connected;
    case 'failed': return s.failed;
    case 'disconnected': return s.disconnected;
    default: return s.idle;
  }
}
