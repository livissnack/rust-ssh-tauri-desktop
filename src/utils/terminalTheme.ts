export function getTerminalTheme(): ITheme {
  const themeId = defaultTheme.value || localStorage.getItem('app-theme-id') || 'monokai-pro';
  const palette = palettes[themeId] ?? palettes['monokai-pro'];

  const style = getComputedStyle(document.documentElement);
  const getProp = (name: string, fallback: string) => style.getPropertyValue(name).trim() || fallback;

  return {
    ...palette,
    background: getProp('--bg-primary', palette.background),
    foreground: getProp('--text-main', palette.foreground),
    cursor: getProp('--accent', palette.cursor ?? palette.foreground),
    selectionBackground: getProp('--accent-20', palette.selectionBackground ?? 'rgba(127,127,127,0.25)'),
  };
}

export function applyTerminalTheme(term: { options: { theme?: ITheme }; refresh: (start: number, end: number) => void; rows: number }) {
  term.options.theme = getTerminalTheme();
  term.refresh(0, term.rows - 1);
}
